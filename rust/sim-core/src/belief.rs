    fn believer_at_stage(stage: i32, belief_id: &str) -> Individual {
        let mut ind = make_ind("i1");
        ind.alive = true;
        ind.language.stage = stage;
        ind.beliefs.insert(belief_id.to_string());
        ind
    }

    #[test]
    fn no_label_before_any_believer_reaches_proto_words() {
        let pop = vec![believer_at_stage(2, "belief_1")];
        assert!(try_label_belief("belief_1", &pop, &crate::language::full_palette()).is_none());
    }

    #[test]
    fn label_appears_once_a_believer_reaches_proto_words() {
        let pop = vec![believer_at_stage(3, "belief_1")];
        assert!(try_label_belief("belief_1", &pop, &crate::language::full_palette()).is_some());
    }

    #[test]
    fn a_believer_of_a_different_belief_does_not_unlock_this_labels() {
        let pop = vec![believer_at_stage(4, "belief_3")];
        assert!(try_label_belief("belief_1", &pop, &crate::language::full_palette()).is_none());
    }

    #[test]
    fn a_dead_capable_believer_does_not_unlock_a_label() {
        let mut ind = believer_at_stage(3, "belief_1");
        ind.alive = false;
        ind.is_dead = true;
        assert!(try_label_belief("belief_1", &[ind], &crate::language::full_palette()).is_none());
    }

    #[test]
    fn empty_palette_never_yields_a_label_even_when_capable() {
        let pop = vec![believer_at_stage(3, "belief_1")];
        assert!(try_label_belief("belief_1", &pop, &PhonemePalette::default()).is_none());
    }

    #[test]
    fn label_is_deterministic_for_the_same_belief_and_palette() {
        let pop = vec![believer_at_stage(3, "belief_1")];
        let palette = crate::language::full_palette();
        assert_eq!(try_label_belief("belief_1", &pop, &palette), try_label_belief("belief_1", &pop, &palette));
    }

    #[test]
    fn different_belief_ids_are_not_all_forced_to_the_same_label() {
        // Same weak-hash property as language::generate_proto_word itself
        // (see its own collision-tolerant test) -- two specific ids can
        // coincidentally collide, so this checks for variety across all six
        // archetypes rather than asserting any one fixed pair always differs.
        let palette = crate::language::full_palette();
        let labels: std::collections::HashSet<Option<String>> = BELIEF_ARCHETYPES
            .iter()
            .map(|(id, ..)| try_label_belief(id, &[believer_at_stage(3, id)], &palette))
            .collect();
        assert!(labels.len() > 1, "expected some variety across the six belief archetypes' labels");
    }
