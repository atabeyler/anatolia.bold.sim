    #[test]
    fn when_two_beliefs_both_cross_the_threshold_the_winner_is_deterministic_not_hashset_order() {
        // Two different HashSets holding the exact same two belief ids,
        // built by inserting them in the opposite order -- HashSet's own
        // iteration order isn't guaranteed to depend on insertion order,
        // but this at least exercises both possible underlying bucket
        // layouts. Sorting before iterating (see check_ritual_emergence)
        // must make "belief_4" win both times, since it sorts before
        // "belief_5" -- not whichever the HashSet happens to yield first.
        let mut members = [make_ind("i1"), make_ind("i2"), make_ind("i3")];
        for m in members.iter_mut() {
            m.beliefs.insert("belief_5".to_string());
            m.beliefs.insert("belief_4".to_string());
        }
        let member_refs: Vec<&Individual> = members.iter().collect();

        let mut existing_a = HashSet::new();
        existing_a.insert("belief_4".to_string());
        existing_a.insert("belief_5".to_string());
        let mut group_a = json!({ "id": "ga", "member_ids": ["i1", "i2", "i3"], "has_ritual": Value::Null });
        let result_a = check_ritual_emergence(&mut group_a, &member_refs, &existing_a, 100).unwrap();

        let mut existing_b = HashSet::new();
        existing_b.insert("belief_5".to_string());
        existing_b.insert("belief_4".to_string());
        let mut group_b = json!({ "id": "gb", "member_ids": ["i1", "i2", "i3"], "has_ritual": Value::Null });
        let result_b = check_ritual_emergence(&mut group_b, &member_refs, &existing_b, 100).unwrap();

        assert_eq!(result_a["belief"], "belief_4");
        assert_eq!(result_b["belief"], "belief_4");
    }

    #[test]
    fn ritual_never_forms_twice_for_the_same_group() {
        let mut members = [make_ind("i1"), make_ind("i2"), make_ind("i3")];
        for m in members.iter_mut() {
            m.beliefs.insert("belief_1".to_string());
        }
        let mut group = json!({ "id": "g1", "member_ids": ["i1", "i2", "i3"], "has_ritual": "belief_1" });
        let mut existing = HashSet::new();
        existing.insert("belief_1".to_string());
        let member_refs: Vec<&Individual> = members.iter().collect();
        assert!(check_ritual_emergence(&mut group, &member_refs, &existing, 100).is_none());
    }

