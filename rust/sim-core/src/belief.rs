/// Purely opaque codes ("belief_1".."belief_6") -- gated by real emergent
/// thresholds (religiosity/IQ/foxp2/tech), but the id itself carries no
/// content at all, not even a neutral descriptive word. This used to borrow
/// real comparative-religion category names as bucketing keys -- harmless
/// in isolation, but every display surface then had to individually
/// remember never to leak one
/// verbatim, and a slip anywhere (event log, report export, a stray debug
/// print) would present this population as having invented that exact
/// real-world religious concept, which it never earned: these are just
/// complexity tiers (see the thresholds below), with no theological content
/// behind the label at all. Making the id itself inert removes that whole
/// class of leak -- there is nothing left to leak. `client/src/utils/i18n.ts`
/// keeps a player-facing description per code (built only from these same
/// mechanical thresholds: required stage/IQ/foxp2/tech, never a religion
/// name) for display before a real label exists. `try_label_belief` below is
/// the only source of that real, player-facing label -- generated by the
/// population's own language, only once it can express one.
pub const BELIEF_ARCHETYPES: &[(&str, i32, f64, f64, &[&str])] = &[
    ("belief_1", 1, 0.0, 0.3, &[]),
    ("belief_2", 2, 0.3, 0.4, &[]),
    ("belief_3", 2, 0.4, 0.5, &[]),
    ("belief_4", 3, 0.5, 0.6, &["pottery"]),
    ("belief_5", 4, 0.6, 0.65, &["writing_system", "mathematics_basic"]),
    ("belief_6", 4, 0.7, 0.7, &["writing_system", "mathematics_basic"]),
];

/// A belief's public label only exists once the population's language has
/// actually reached the point of expressing "god"/"spirit" concepts
/// (proto-words, stage >= 3 -- see `language::CORE_CONCEPTS`). Before that,
/// the archetype is mechanically real (someone holds it, it can spread,
/// it can anchor a ritual) but literally has no name yet: nobody in the
/// population has the words to have coined one. Deterministic per
/// (belief_id, this simulation's phoneme palette) -- never a fixed
/// real-world religion name.
pub fn try_label_belief(belief_id: &str, population: &[Individual], palette: &PhonemePalette) -> Option<String> {
    let any_capable = population.iter().any(|i| i.alive && !i.is_dead && i.beliefs.contains(belief_id) && i.language.stage >= 3);
    if !any_capable {
        return None;
    }
    let raw = crate::language::generate_proto_word(belief_id, "belief", palette);
    if raw.is_empty() {
        return None;
    }
    let mut chars = raw.chars();
    chars.next().map(|first| first.to_uppercase().collect::<String>() + chars.as_str())
}

fn religiosity_of(p: &crate::types::Phenotype) -> f64 {
    // `> 0.0` here is a sentinel for "not yet computed" (compute_phenotype
    // always populates a real value in production, so this branch exists
    // only to give tests/fixtures using Phenotype::default() a sane fallback
    // rather than a hard 0.0 susceptibility). A genuinely-computed religiosity
    // landing on exactly 0.0 (belief_capacity == 0.0 and serotonin == 1.0 at
    // the same time) would fall through to this same fallback, but that's an
    // astronomically unlikely coincidence for continuous, randomly-seeded
    // genome values -- not worth an Option<f64> plumbed through every
    // Phenotype construction site to close.
    if p.religiosity > 0.0 {
        p.religiosity
    } else {
        (p.anxiety + p.curiosity) / 2.0
    }
}

pub fn try_form_belief(individual: &mut Individual, existing_beliefs: &mut HashSet<String>, discovered_techs: &HashSet<String>, world_state: &Value, sim_day: i32) -> Option<Value> {
    let p = &individual.phenotype;
    let religiosity = religiosity_of(p);
    let env_gain = 1.0
        + if world_state.get("recent_disaster").is_some() { 5.0 } else { 0.0 }
        + (1.0 - world_state.get("food_abundance").and_then(Value::as_f64).unwrap_or(0.5)).max(0.0) * 3.0;
    let reflection = individual.extra.get("_beliefReflection").and_then(Value::as_f64).unwrap_or(0.0) + env_gain;
    let threshold = 100.0 / (religiosity * p.fluid_intelligence).max(0.1);
    individual.extra.insert("_beliefReflection".to_string(), json!(reflection));
    if reflection < threshold {
        return None;
    }
    let lang_stage = individual.language.stage;
    let mut eligible: Vec<_> = BELIEF_ARCHETYPES
        .iter()
        .filter(|(name, lang_min, iq_min, foxp2_min, requires_tech)| {
            !existing_beliefs.contains(*name)
                && lang_stage >= *lang_min
                && p.fluid_intelligence >= *iq_min
                && individual.language.foxp2_expression >= *foxp2_min
                && !requires_tech.iter().any(|t| !discovered_techs.contains(*t))
        })
        .collect();
    if eligible.is_empty() {
        return None;
    }
    eligible.sort_by_key(|a| a.1);
    let (belief_id, stage, _, _, _) = eligible[0];
    existing_beliefs.insert((*belief_id).to_string());
    individual.beliefs.insert((*belief_id).to_string());
    individual.extra.insert("_beliefReflection".to_string(), json!(0));
    Some(json!({
        "type": "belief_formed",
        "belief_id": belief_id,
        "founder_id": individual.id,
        "day": sim_day,
        "importance": if *stage >= 3 { "high" } else { "medium" },
    }))
}

fn distance(ax: f64, ay: f64, bx: f64, by: f64) -> f64 {
    ((ax - bx).powi(2) + (ay - by).powi(2)).sqrt()
}

/// Belief only spreads to someone who is in a group with a believer, or
/// physically nearby one -- never to an arbitrary, unconnected individual.
pub fn update_belief_spread(population: &mut [Individual], existing_beliefs: &HashSet<String>, groups: &mut [Value], sim_day: i32) -> Vec<Value> {
    if existing_beliefs.is_empty() {
        return Vec::new();
    }
    let mut events = Vec::new();

    // Snapshot of positions/group_id/beliefs per belief, computed before any
    // mutation. Carrying each holder's own belief set here (instead of just
    // "has some belief") means the per-belief loop below can check it
    // directly instead of re-scanning the whole population for every holder
    // for every belief -- that re-scan was an O(beliefs * population^2) cost
    // that grew sharply once a group had more than a handful of believers.
    #[allow(clippy::type_complexity)]
    let holders: Vec<(String, f64, f64, Option<String>, HashSet<String>)> = population
        .iter()
        .filter(|i| !i.beliefs.is_empty())
        .map(|i| (i.id.clone(), i.x, i.y, i.group_id.clone(), i.beliefs.clone()))
        .collect();

    for belief in existing_beliefs {
        let groups_with_belief: HashSet<&str> = holders
            .iter()
            .filter(|(.., beliefs)| beliefs.contains(belief))
            .filter_map(|(_, _, _, gid, _)| gid.as_deref())
            .collect();
        let believer_positions: Vec<(f64, f64)> = holders
            .iter()
            .filter(|(.., beliefs)| beliefs.contains(belief))
            .map(|(_, x, y, ..)| (*x, *y))
            .collect();

        for individual in population.iter_mut() {
            if individual.beliefs.contains(belief) {
                continue;
            }
            let in_group = individual.group_id.as_deref().is_some_and(|gid| groups_with_belief.contains(gid));
            let nearby = !in_group && believer_positions.iter().any(|(bx, by)| distance(*bx, *by, individual.x, individual.y) < 2.0);
            if !in_group && !nearby {
                continue;
            }
            let susceptibility = religiosity_of(&individual.phenotype);
            let exposure = individual.extra.entry("_beliefExposure".to_string()).or_insert_with(|| json!({}));
            let current = exposure.get(belief).and_then(Value::as_i64).unwrap_or(0) + 1;
            if let Some(obj) = exposure.as_object_mut() {
                obj.insert(belief.clone(), json!(current));
            }
            let threshold = 80.0 / susceptibility.max(0.2);
            if (current as f64) < threshold {
                continue;
            }
            if let Some(obj) = individual.extra.get_mut("_beliefExposure").and_then(Value::as_object_mut) {
                obj.remove(belief);
            }
            individual.beliefs.insert(belief.clone());
            let group_id = individual.group_id.clone();
            if let Some(gid) = &group_id {
                if let Some(group) = groups.iter_mut().find(|g| g.get("id").and_then(Value::as_str) == Some(gid.as_str())) {
                    let tension = group.get("internal_tension").and_then(Value::as_f64).unwrap_or(0.5);
                    if let Some(obj) = group.as_object_mut() {
                        obj.insert("internal_tension".to_string(), json!((tension - 0.05).max(0.0)));
                    }
                }
            }
            events.push(json!({
                "type": "belief_spread",
                "belief_id": belief,
                "individual_id": individual.id,
                "group_id": group_id,
                "day": sim_day,
                "importance": "low"
            }));
        }
    }
    events
}

/// Fires at most once per group -- `group.has_ritual` gates re-emission once a
/// ritual has already emerged, mirroring the JS original (without this, the
/// same >60%-belief-share condition would re-fire the event every tick).
/// `members` is this group's own membership, already resolved by the caller
/// (see tick.rs) -- letting each call filter the *entire* population itself
/// was an O(groups * population) cost that got sharply worse as both grew.
pub fn check_ritual_emergence(group: &mut Value, members: &[&Individual], existing_beliefs: &HashSet<String>, sim_day: i32) -> Option<Value> {
    if group.get("has_ritual").is_some_and(|v| !v.is_null()) {
        return None;
    }
    if members.len() < 3 {
        return None;
    }
    // Sorted rather than iterated in HashSet's own (arbitrary, run-to-run
    // unstable) order: when multiple beliefs cross the 60% cohesion
    // threshold in the same tick, which one becomes "the" ritual must be a
    // deterministic function of which beliefs exist, not of this process's
    // particular hash-bucket layout -- otherwise identical population states
    // could pick a different winning ritual across separate runs/replays.
    let mut existing_beliefs: Vec<&String> = existing_beliefs.iter().collect();
    existing_beliefs.sort();
    for belief in existing_beliefs {
        let count = members.iter().filter(|m| m.beliefs.contains(belief)).count();
        if count as f64 / members.len() as f64 > 0.6 {
            if let Some(obj) = group.as_object_mut() {
                obj.insert("has_ritual".to_string(), json!(belief));
                obj.insert("ritual_cohesion".to_string(), json!(0.1));
            }
            return Some(json!({
                "type": "ritual_emerged",
                "group_id": group.get("id").cloned().unwrap_or(Value::Null),
                "belief": belief,
                "day": sim_day,
                "importance": "medium"
            }));
        }
    }
    None
}

